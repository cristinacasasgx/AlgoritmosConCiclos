// 6.	Recorrido de arreglos: Define un arreglo de nombres y utiliza un bucle para mostrar cada nombre individualmente en la pantalla.

function arregloNombres() {
    let nombres = ["Sofia", "Sara", "Emilia", "Matilde"];
    for (let i = 0; i < nombres.length; i++) {
        console.log(nombres[i]);
    }
}
arregloNombres();
