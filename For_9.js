//9.	Tabla de multiplicar: Genera la tabla de multiplicar del número 5 (del 1 al 10) utilizando la actualización del contador en cada iteración.

function tablaMultiplicarCinco() {
    for (let i = 1; i <= 10; i++) {
        console.log("5 x " + i + " = " + (5 * i));
    }
}
tablaMultiplicarCinco();
