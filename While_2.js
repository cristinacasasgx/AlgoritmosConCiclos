//2. El Contenedor de Manzanas: Simula el llenado de un contenedor. Debes imprimir "Manzana número X" desde la 1 hasta llegar a la 1000

function contenedorManzanas() {
    let manzana = 1;

    while (manzana <= 1000) {
        console.log("Manzana número " + manzana);
        manzana++;
    }
}
contenedorManzanas();
